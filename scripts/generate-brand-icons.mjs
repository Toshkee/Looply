/**
 * Extracts the brand icons listed in brands.config.json from the simple-icons
 * package into a small, bundle-friendly TypeScript module. Only the icons the
 * app uses ship with it; nothing is fetched at runtime.
 *
 * Usage: npm run brands
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as simpleIcons from 'simple-icons';

const here = dirname(fileURLToPath(import.meta.url));
const config = JSON.parse(readFileSync(join(here, 'brands.config.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(here, '..', 'node_modules', 'simple-icons', 'package.json'), 'utf8')).version;
const bySlug = new Map(Object.values(simpleIcons).filter((icon) => icon && icon.slug).map((icon) => [icon.slug, icon]));

const entries = Object.entries(config.brands).map(([slug, aliases]) => {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no icon "${slug}"`);
  for (const alias of aliases) {
    if (!/^[a-z0-9]+$/.test(alias)) throw new Error(`Alias "${alias}" must be lowercase letters and digits`);
  }
  return { slug, title: icon.title, hex: `#${icon.hex}`, path: icon.path, aliases };
});

const output = `// Generated by scripts/generate-brand-icons.mjs from simple-icons@${version} (CC0-1.0).
// Do not edit by hand. Logos remain trademarks of their respective owners.

export interface BrandIcon {
  slug: string;
  title: string;
  /** Brand color. */
  hex: string;
  /** SVG path in a 24×24 viewBox. */
  path: string;
  /** Normalized names that identify the brand. */
  aliases: readonly string[];
}

export const BRAND_ICONS: readonly BrandIcon[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(here, '..', 'src', 'assets', 'brandIcons.generated.ts'), output);
console.log(`Wrote ${entries.length} brand icons from simple-icons@${version}.`);
