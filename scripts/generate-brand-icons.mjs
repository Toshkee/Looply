/**
 * Extracts the brand icons listed in brands.config.json into a small,
 * bundle-friendly TypeScript module. Only the icons the app uses ship with it;
 * nothing is fetched at runtime.
 *
 * - `brands`: logos from the simple-icons package.
 * - `extraBrands`: logos simple-icons no longer carries, from scripts/brand-svgs
 *   (one path per file; sources and licenses in its LICENSES.md).
 * - `initialBrands`: no free vector logo; the app shows the initial on the brand color.
 *
 * Usage: npm run brands
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as simpleIcons from 'simple-icons';

const here = dirname(fileURLToPath(import.meta.url));
const config = JSON.parse(readFileSync(join(here, 'brands.config.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(here, '..', 'node_modules', 'simple-icons', 'package.json'), 'utf8')).version;
const bySlug = new Map(Object.values(simpleIcons).filter((icon) => icon && icon.slug).map((icon) => [icon.slug, icon]));

function checkAliases(aliases) {
  for (const alias of aliases) {
    if (!/^[a-z0-9]+$/.test(alias)) throw new Error(`Alias "${alias}" must be lowercase letters and digits`);
  }
  return aliases;
}

function checkHex(slug, hex) {
  if (!/^#[0-9A-F]{6}$/.test(hex)) throw new Error(`"${slug}" needs an uppercase #RRGGBB color, got "${hex}"`);
  return hex;
}

/** The single path of a vendored SVG; anything more complex would not render as one glyph. */
function readSvgGlyph(slug) {
  const svg = readFileSync(join(here, 'brand-svgs', `${slug}.svg`), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (!viewBox || paths.length !== 1 || /fill-rule|<(g|circle|rect|polygon|ellipse)\b/.test(svg)) {
    throw new Error(`brand-svgs/${slug}.svg must be a single <path> with a viewBox`);
  }
  return { path: paths[0], viewBox };
}

const entries = [
  ...Object.entries(config.brands).map(([slug, aliases]) => {
    const icon = bySlug.get(slug);
    if (!icon) throw new Error(`simple-icons has no icon "${slug}"`);
    return { slug, title: icon.title, hex: `#${icon.hex}`, glyph: { path: icon.path, viewBox: '0 0 24 24' }, aliases: checkAliases(aliases) };
  }),
  ...Object.entries(config.extraBrands).map(([slug, { title, hex, aliases }]) => ({
    slug,
    title,
    hex: checkHex(slug, hex),
    glyph: readSvgGlyph(slug),
    aliases: checkAliases(aliases),
  })),
  ...Object.entries(config.initialBrands).map(([slug, { title, hex, aliases }]) => ({
    slug,
    title,
    hex: checkHex(slug, hex),
    glyph: null,
    aliases: checkAliases(aliases),
  })),
];

const slugs = entries.map((entry) => entry.slug);
const duplicate = slugs.find((slug, index) => slugs.indexOf(slug) !== index);
if (duplicate) throw new Error(`Brand "${duplicate}" is listed twice`);

const output = `// Generated by scripts/generate-brand-icons.mjs from simple-icons@${version} (CC0-1.0)
// and scripts/brand-svgs (CoreUI Brands, CC0-1.0; Boxicons, MIT, Copyright (c) 2026 Boxicons;
// see scripts/brand-svgs/LICENSES.md). Do not edit by hand.
// Logos remain trademarks of their respective owners.

export interface BrandIcon {
  slug: string;
  title: string;
  /** Brand color. */
  hex: string;
  /** Single-color logo, or \`null\` when the brand is shown as its initial on the brand color. */
  glyph: { path: string; viewBox: string } | null;
  /** Normalized names that identify the brand. */
  aliases: readonly string[];
}

export const BRAND_ICONS: readonly BrandIcon[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(here, '..', 'src', 'assets', 'brandIcons.generated.ts'), output);
const logos = entries.filter((entry) => entry.glyph).length;
console.log(`Wrote ${logos} brand logos and ${entries.length - logos} brand initials (simple-icons@${version} + brand-svgs).`);
